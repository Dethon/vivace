//! The icon in the Windows notification area that keeps Vivace at hand
//! while its window is closed. Other systems have no tray here: on Linux it
//! would need GTK, which costs more memory than the rest of the app.

use slint::ComponentHandle;

use crate::{MainWindow, Player};

/// Whether this system gets a tray icon.
pub const SUPPORTED: bool = cfg!(windows);

/// Shows the window again after it was closed to the tray.
pub fn show_window(ui: &MainWindow) {
    if let Err(error) = ui.show() {
        log::warn!("couldn't show the window: {error}");
    }
    ui.window().set_minimized(false);
}

/// What the tray asks the app to do.
#[cfg_attr(not(windows), allow(dead_code))]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Action {
    Show,
    Toggle,
    Next,
    Previous,
    Quit,
}

#[cfg_attr(not(windows), allow(dead_code))]
fn act(ui: &MainWindow, action: Action) {
    let player = ui.global::<Player>();
    match action {
        Action::Show => show_window(ui),
        Action::Toggle => player.invoke_toggle(),
        Action::Next => player.invoke_next(),
        Action::Previous => player.invoke_previous(),
        Action::Quit => {
            // Ends the event loop, after which `main` lets the backend save
            // where an episode was left.
            _ = slint::quit_event_loop();
        }
    }
}

#[cfg(windows)]
pub use windows::Tray;

#[cfg(windows)]
mod windows {
    use tray_icon::menu::{Menu, MenuEvent, MenuId, MenuItem, PredefinedMenuItem};
    use tray_icon::{
        Icon, MouseButton, MouseButtonState, TrayIcon, TrayIconBuilder, TrayIconEvent,
    };

    use slint::ComponentHandle;

    use super::{Action, act};
    use crate::MainWindow;

    pub struct Tray {
        icon: TrayIcon,
    }

    impl Tray {
        pub fn new(ui: &MainWindow) -> Result<Self, Box<dyn std::error::Error>> {
            // Generated by `cargo run -p vivace --example icon`.
            const PNG: &[u8] = include_bytes!("../assets/icon.png");
            let image = image::load_from_memory_with_format(PNG, image::ImageFormat::Png)?;
            let image = image.into_rgba8();
            let (width, height) = image.dimensions();
            let icon = Icon::from_rgba(image.into_raw(), width, height)?;

            let items = [
                (MenuItem::new("Show Vivace", true, None), Action::Show),
                (MenuItem::new("Play / Pause", true, None), Action::Toggle),
                (MenuItem::new("Next", true, None), Action::Next),
                (MenuItem::new("Previous", true, None), Action::Previous),
                (MenuItem::new("Quit Vivace", true, None), Action::Quit),
            ];
            let menu = Menu::new();
            menu.append(&items[0].0)?;
            menu.append(&PredefinedMenuItem::separator())?;
            for (item, _) in &items[1..4] {
                menu.append(item)?;
            }
            menu.append(&PredefinedMenuItem::separator())?;
            menu.append(&items[4].0)?;

            let icon = TrayIconBuilder::new()
                .with_icon(icon)
                .with_tooltip("Vivace")
                .with_menu(Box::new(menu))
                .with_menu_on_left_click(false)
                .build()?;

            // The handlers run on the thread pumping window messages; the
            // window is reached through the event loop all the same.
            let actions: Vec<(MenuId, Action)> = items
                .iter()
                .map(|(item, action)| (item.id().clone(), *action))
                .collect();
            let window = ui.as_weak();
            MenuEvent::set_event_handler(Some(move |event: MenuEvent| {
                if let Some(&(_, action)) = actions.iter().find(|(id, _)| *id == event.id) {
                    _ = window.upgrade_in_event_loop(move |ui| act(&ui, action));
                }
            }));
            let window = ui.as_weak();
            TrayIconEvent::set_event_handler(Some(move |event: TrayIconEvent| {
                if let TrayIconEvent::Click {
                    button: MouseButton::Left,
                    button_state: MouseButtonState::Up,
                    ..
                } = event
                {
                    _ = window.upgrade_in_event_loop(|ui| act(&ui, Action::Show));
                }
            }));
            Ok(Self { icon })
        }

        /// Names what is playing when the pointer rests on the icon.
        pub fn set_tooltip(&self, text: &str) {
            if let Err(error) = self.icon.set_tooltip(Some(text)) {
                log::warn!("couldn't update the tray tooltip: {error}");
            }
        }
    }

    impl Drop for Tray {
        fn drop(&mut self) {
            MenuEvent::set_event_handler(None::<fn(MenuEvent)>);
            TrayIconEvent::set_event_handler(None::<fn(TrayIconEvent)>);
        }
    }
}

/// Stands in where there is no tray; never constructed.
#[cfg(not(windows))]
pub struct Tray(std::convert::Infallible);

#[cfg(not(windows))]
impl Tray {
    pub fn new(_: &MainWindow) -> Result<Self, Box<dyn std::error::Error>> {
        Err("this system has no tray".into())
    }

    pub fn set_tooltip(&self, _: &str) {}
}
